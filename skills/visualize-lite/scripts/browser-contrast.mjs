#!/usr/bin/env node
// Browser-contrast sidecar for detect.mjs.
//
// `detect.mjs` is zero-dep and structural — it parses CSS as text and
// runs WCAG math through culori. That misses three cases the static
// approach can't see:
//   1. var(--foo) colors that the browser resolves but culori doesn't.
//   2. Cross-rule cascade (text rule sets `color`, ancestor sets
//      `background` — no single `{}` block carries both).
//   3. Per-theme computed styles (`:root` vs `[data-theme="dark"]`).
// A real browser closes all three at once via getComputedStyle().
//
// This sidecar launches headless Chrome via the bundled puppeteer-core,
// injects axe-core, runs `color-contrast`, and emits findings as NDJSON
// in the same shape `detect.mjs` uses. The `review` verb unions the two
// streams without schema reconciliation.
//
// Runtime requirements:
//   - Node 22.12+ (puppeteer-core@25 declares engines.node >= 22.12.0).
//   - Either Google Chrome installed locally, OR outbound HTTPS to
//     storage.googleapis.com so @puppeteer/browsers can download a
//     managed Chromium on first run.
//
// Trust model:
//   Inputs are expected to be trusted artifacts authored by the user
//   or their team — typically generated by the visualize skill itself,
//   or hand-edited preview templates. The sidecar launches a real
//   browser with JavaScript and outbound network enabled (spec
//   decision #11 — "measure what users see, not what loads offline").
//   Do NOT point this at hostile HTML from an unknown source: the page
//   can run scripts, fetch remote resources, and probe local network
//   inside Chrome's sandbox.
//
// Usage:
//   node browser-contrast.mjs ./artifact.html
//   node browser-contrast.mjs --json ./artifact.html
//   node browser-contrast.mjs --strict ./artifact.html
//   node browser-contrast.mjs --list-rules [--json]
//
// Env vars:
//   VISUALIZE_PUPPETEER_CACHE_DIR    Override the managed-Chromium cache
//                                    location. Default:
//                                    ~/.cache/visualize-skill/puppeteer/
//   VISUALIZE_SKIP_SYSTEM_CHROME=1   Skip system-Chrome detection and
//                                    force the managed-install path.
//                                    Test-only hook — used by the
//                                    cold-cache acceptance scenario.
//
// Exit codes:
//   0 — clean (or no errors when --strict)
//   1 — unreadable input / infrastructure failure
//   2 — error findings present and --strict set

import { existsSync, realpathSync, statSync } from 'node:fs';
import { homedir } from 'node:os';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { setTimeout as sleep } from 'node:timers/promises';
import {
  puppeteer,
  computeSystemExecutablePath,
  install,
  resolveBuildId,
  detectBrowserPlatform,
  Browser,
  BrowserTag,
} from './vendor/puppeteer.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const AXE_PATH = resolve(__dirname, 'vendor', 'axe.min.js');

const CACHE_DIR =
  process.env.VISUALIZE_PUPPETEER_CACHE_DIR ||
  join(homedir(), '.cache', 'visualize-skill', 'puppeteer');

// ============================================================
// Rule catalogue
// ============================================================

// Single synthetic rule. axe's own rule id (`color-contrast`) is carried
// inside each finding's `snippet` for traceability, but `ruleId` stays
// constant so downstream filtering (`--skip`, dedup) treats this as one
// concept.
const RULES = [
  {
    id: 'a11y/browser-contrast',
    category: 'a11y',
    defaultSeverity: 'error',
    description: 'Text/background contrast below WCAG AA, computed in a real browser via axe-core.',
  },
];

// axe `impact` → detect.mjs `severity`. Matches detect.mjs's three-tier
// model so the union with Layer 1 reads from one rulebook.
const IMPACT_TO_SEVERITY = {
  critical: 'error',
  serious: 'error',
  moderate: 'warn',
  minor: 'info',
};

// ============================================================
// Typed errors — keep the main()-level branches off message regex.
// ============================================================

class ChromeAcquireError extends Error {
  constructor(message) {
    super(message);
    this.name = 'ChromeAcquireError';
  }
}

class LoadError extends Error {
  constructor(message) {
    super(message);
    this.name = 'LoadError';
  }
}

// ============================================================
// Chrome acquisition
// ============================================================

async function resolveChromeExecutable() {
  try {
    if (process.env.VISUALIZE_SKIP_SYSTEM_CHROME !== '1') {
      try {
        return computeSystemExecutablePath({
          browser: Browser.CHROME,
          channel: 'stable',
        });
      } catch {
        // Fall through to managed install. computeSystemExecutablePath
        // reads platform-specific install locations directly (e.g.
        // /Applications/Google Chrome.app on macOS, Program Files on
        // Windows, distro-standard paths on Linux) — NOT $PATH.
      }
    }
    const platform = detectBrowserPlatform();
    if (!platform) {
      throw new Error('unsupported platform for managed Chromium fallback');
    }
    const buildId = await resolveBuildId(Browser.CHROME, platform, BrowserTag.STABLE);
    const result = await install({
      browser: Browser.CHROME,
      cacheDir: CACHE_DIR,
      buildId,
      buildIdAlias: BrowserTag.STABLE,
    });
    return result.executablePath;
  } catch (err) {
    throw new ChromeAcquireError(err.message);
  }
}

// ============================================================
// Finding construction
// ============================================================

function mapViolationToFinding(violation, node) {
  const severity = IMPACT_TO_SEVERITY[violation.impact] || 'error';
  const data = node.any?.[0]?.data || {};
  const ratio = typeof data.contrastRatio === 'number'
    ? data.contrastRatio.toFixed(2)
    : null;
  const fg = data.fgColor || null;
  const bg = data.bgColor || null;
  // axe encodes `expectedContrastRatio` as `'4.5:1'` (string with the
  // trailing `:1`). Strip it so the snippet reads `threshold 4.5` per
  // spec §Output schema example.
  const thresholdRaw = data.expectedContrastRatio || null;
  const threshold = thresholdRaw && typeof thresholdRaw === 'string'
    ? thresholdRaw.replace(/:1$/, '')
    : thresholdRaw;

  const message = ratio
    ? `Contrast ratio ${ratio} — below WCAG AA (4.5:1 body, 3:1 large).`
    : `Contrast below WCAG AA.`;

  const snippetParts = ['axe:color-contrast'];
  const detail = [];
  if (fg) detail.push(`fg ${fg}`);
  if (bg) detail.push(`bg ${bg}`);
  if (ratio) detail.push(`ratio ${ratio}`);
  if (threshold) detail.push(`threshold ${threshold}`);
  const snippet = detail.length
    ? `${snippetParts[0]} — ${detail.join(', ')}`
    : `${snippetParts[0]} — ${(node.failureSummary || '').split('\n')[0]}`;

  return {
    ruleId: 'a11y/browser-contrast',
    category: 'a11y',
    severity,
    locator: (node.target || []).join(' '),
    message,
    snippet,
  };
}

function mapIncompleteToFinding(entry, node) {
  // axe `incomplete` entries don't carry `impact`. Use `failureSummary`
  // to extract the "could not be determined due to ..." clause as the
  // reason. The snippet shape is distinct (`(needs-review)`) so strict
  // mode doesn't gate on these.
  const summary = node.failureSummary || '';
  // First non-empty line minus the "Fix all of the following:" /
  // "Fix any of the following:" prefix axe likes to prepend.
  const firstReason = summary
    .split('\n')
    .map((s) => s.trim())
    .find((s) => s && !/^Fix /i.test(s)) || 'reason unknown';
  return {
    ruleId: 'a11y/browser-contrast',
    category: 'a11y',
    severity: 'warn',
    locator: (node.target || []).join(' '),
    message: firstReason,
    snippet: `axe:color-contrast (needs-review) — ${firstReason}`,
  };
}

// ============================================================
// Per-file detection
// ============================================================

async function findingsForFile(browser, filePath) {
  const page = await browser.newPage();
  try {
    const fileUrl = pathToFileURL(resolve(filePath)).href;
    // page.waitForTimeout was removed in puppeteer@22 — use node:timers
    // setTimeout instead. document.fonts.ready resolves once webfonts
    // settle; the 100ms tail is a fixed buffer for late-applied CSS
    // (transitions, ResizeObserver-driven theme swaps, etc.).
    try {
      await page.goto(fileUrl, { waitUntil: 'domcontentloaded' });
      await page.evaluate(() => document.fonts.ready);
      await sleep(100);
      await page.addScriptTag({ path: AXE_PATH });
    } catch (err) {
      throw new LoadError(err.message);
    }
    // The narrow catch: only axe's evaluation inside the page is
    // recoverable as a synthetic finding per spec §Operational
    // behavior. Failures in goto / fonts.ready / addScriptTag are
    // infrastructure (above) — they abort the run.
    let axeResult;
    try {
      axeResult = await page.evaluate(async () => {
        return await window.axe.run(document, {
          runOnly: ['color-contrast'],
        });
      });
    } catch (err) {
      return [{
        ruleId: 'a11y/browser-contrast',
        category: 'a11y',
        severity: 'warn',
        locator: 'engine',
        message: `axe-core errored: ${err.message}`,
        snippet: 'axe:color-contrast (engine-error)',
      }];
    }
    const violations = (axeResult.violations || []).flatMap((v) =>
      (v.nodes || []).map((n) => mapViolationToFinding(v, n)),
    );
    const needsReview = (axeResult.incomplete || []).flatMap((v) =>
      (v.nodes || []).map((n) => mapIncompleteToFinding(v, n)),
    );
    return [...violations, ...needsReview];
  } finally {
    await page.close().catch(() => {});
  }
}

// ============================================================
// Output
// ============================================================

function emitFinding(json, file, finding) {
  if (json) {
    process.stdout.write(JSON.stringify({ type: 'finding', file, ...finding }) + '\n');
  } else {
    const sym = { error: '×', warn: '⚠', info: '·' }[finding.severity] || '·';
    console.log(`  ${sym} ${finding.ruleId.padEnd(36)}  ${finding.locator || ''}`);
    console.log(`      ${finding.message}`);
    if (finding.snippet) console.log(`      ${finding.snippet}`);
  }
}

function emitSummary(json, counts, filesScanned, durationMs, strict) {
  const { errors, warnings, info } = counts;
  if (json) {
    process.stdout.write(JSON.stringify({
      type: 'summary',
      errors, warnings, info,
      rulesRan: RULES.length,
      filesScanned,
      durationMs,
    }) + '\n');
    return;
  }
  const total = errors + warnings + info;
  if (total === 0) {
    console.log(`\nOK · ${RULES.length} rule clean across ${filesScanned} file(s) · ${durationMs}ms`);
    return;
  }
  const tag = strict && errors > 0 ? 'exit 2' : 'exit 0';
  console.log(`\n${tag} · ${errors} error · ${warnings} warning · ${info} info · ${durationMs}ms`);
}

// ============================================================
// CLI
// ============================================================

function printUsage() {
  console.log('Usage: node browser-contrast.mjs [options] <html-file>...');
  console.log('Options:');
  console.log('  --json               NDJSON output (per-finding lines + summary)');
  console.log('  --strict             exit 2 on any error finding');
  console.log('  --list-rules         print the rule catalogue and exit');
  console.log('  --list-rules --json  same, as a single JSON array');
}

function listRules(asJson) {
  if (asJson) {
    console.log(JSON.stringify(RULES, null, 2));
    return;
  }
  const sevSym = { error: '×', warn: '⚠', info: '·' };
  for (const r of RULES) {
    console.log(`${sevSym[r.defaultSeverity] || '·'} ${r.id.padEnd(36)} ${r.description}`);
  }
  console.log(`\n${RULES.length} rule(s) total`);
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length === 0 || args.includes('--help') || args.includes('-h')) {
    printUsage();
    process.exit(0);
  }
  if (args.includes('--list-rules')) {
    listRules(args.includes('--json'));
    process.exit(0);
  }
  let strict = false;
  let json = false;
  const files = [];
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a === '--strict') strict = true;
    else if (a === '--json') json = true;
    else if (a.startsWith('--')) {
      console.error(`unknown flag: ${a}`);
      process.exit(1);
    } else {
      files.push(a);
    }
  }
  if (files.length === 0) {
    printUsage();
    process.exit(0);
  }

  for (const file of files) {
    if (!existsSync(file)) {
      console.error(`error: file not found: ${file}`);
      process.exit(1);
    }
    if (!statSync(file).isFile()) {
      console.error(`error: not a file: ${file}`);
      process.exit(1);
    }
  }

  const startedAt = Date.now();
  const executablePath = await resolveChromeExecutable();
  const browser = await puppeteer.launch({ executablePath, headless: true });

  const counts = { errors: 0, warnings: 0, info: 0 };
  // Cache outcomes so we still close the browser cleanly before
  // exit(1). Calling process.exit inside the loop skips browser.close.
  let loadFailureMessage = null;
  let browserDisconnected = false;
  let filesProcessed = 0;
  try {
    for (const file of files) {
      let findings;
      try {
        findings = await findingsForFile(browser, file);
      } catch (err) {
        // Spec §Operational behavior row "Browser disconnects
        // mid-list": emit summary with partial counts, exit 1. Check
        // this *first* — a Chrome crash during goto/fonts/script
        // injection bubbles as LoadError but the underlying cause is
        // a disconnect, not an unreadable page.
        if (!browser.isConnected()) {
          browserDisconnected = true;
          break;
        }
        if (err instanceof LoadError) {
          // Spec §Operational behavior row "page.goto rejects": abort
          // the run, remaining files not scanned.
          loadFailureMessage = `error: failed to load ${file}: ${err.message}`;
          break;
        }
        throw err;
      }
      filesProcessed++;
      for (const f of findings) {
        if (f.severity === 'error') counts.errors++;
        else if (f.severity === 'warn') counts.warnings++;
        else counts.info++;
        emitFinding(json, file, f);
      }
    }
  } finally {
    await browser.close().catch(() => {});
  }

  if (loadFailureMessage) {
    console.error(loadFailureMessage);
    process.exit(1);
  }

  const durationMs = Date.now() - startedAt;
  if (browserDisconnected) {
    emitSummary(json, counts, filesProcessed, durationMs, strict);
    console.error('error: browser disconnected mid-run');
    process.exit(1);
  }

  emitSummary(json, counts, files.length, durationMs, strict);
  process.exit(strict && counts.errors > 0 ? 2 : 0);
}

// Entry-point check: compare real paths on both sides so the script
// runs when invoked through a symlink (e.g. ~/.claude/skills/visualize/
// → ~/.agents/skills/visualize/). The naive equality
// `import.meta.url === file://${process.argv[1]}` fails on symlinks
// because Node resolves the symlink in import.meta.url but not in argv.
function isMain() {
  try {
    return realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1]);
  } catch {
    return false;
  }
}

if (isMain()) {
  main().catch((err) => {
    // Chromium-acquisition failures bubble as ChromeAcquireError (see
    // resolveChromeExecutable). Anything else is an unexpected crash.
    if (err instanceof ChromeAcquireError) {
      console.error(`error: failed to acquire Chrome: ${err.message}`);
    } else {
      console.error(`crash: ${err.message}`);
    }
    process.exit(1);
  });
}
